class LumberjackComponent extends PositionComponent
    with TapCallbacks, HasGameReference<IslandGame> {
  /// The backing row on the server, once the build call succeeds (or set
  /// directly for buildings loaded from the backend on startup).
  int? backendId;

  final int ownerId;
  final Color ownerColor;

  LumberjackComponent({
    required Vector2 worldPosition,
    required double islandRadius,
    required this.ownerId,
    required this.ownerColor,
  }) : super(
          anchor: Anchor.center,
          position: worldPosition,
          size: Vector2.all(islandRadius * 0.2),
          priority: 5,
        );

  @override
  void render(Canvas canvas) {
    final cabinPaint = Paint()..color = const Color(0xFF5D4037);
    final roofPaint = Paint()..color = const Color(0xFF3E2723);
    final logPaint = Paint()..color = const Color(0xFFA1887F);
    final logEndPaint = Paint()..color = const Color(0xFFD7B899);

    final cabinRect = Rect.fromLTWH(size.x * 0.1, size.y * 0.4, size.x * 0.55, size.y * 0.5);
    canvas.drawRect(cabinRect, cabinPaint);

    final roofPath = Path()
      ..moveTo(size.x * 0.04, size.y * 0.4)
      ..lineTo(size.x * 0.37, size.y * 0.12)
      ..lineTo(size.x * 0.7, size.y * 0.4)
      ..close();
    canvas.drawPath(roofPath, roofPaint);

    // A small stack of cut logs beside the cabin.
    final logRadius = size.x * 0.09;
    final logCenters = [
      Offset(size.x * 0.78, size.y * 0.78),
      Offset(size.x * 0.93, size.y * 0.78),
      Offset(size.x * 0.855, size.y * 0.63),
    ];
    for (final center in logCenters) {
      canvas.drawCircle(center, logRadius, logPaint);
      canvas.drawCircle(center, logRadius * 0.55, logEndPaint);
    }

    _drawOwnerFlag(canvas, size, ownerColor);
  }

  @override
  void onTapDown(TapDownEvent event) {
    super.onTapDown(event);
    event.continuePropagation = false;
    game.onLumberjackTapped?.call(this);
  }
}

class BoatComponent extends PositionComponent
    with TapCallbacks, HasGameReference<IslandGame>, PathFollower {
  @override
  final double speed;
  bool isSelected = false;

  /// The backing row on the server.
  int? backendId;

  final int ownerId;

  BoatComponent({
    required Vector2 startPosition,
    required double islandRadius,
    required this.ownerId,
  })  : speed = islandRadius * 0.6,
        super(
          anchor: Anchor.center,
          position: startPosition,
          size: Vector2(islandRadius * 0.16, islandRadius * 0.1),
          priority: 5,
        );

  /// Follows a sequence of waypoints in order (see [IslandGame._seaPathTo]),
  /// calling [onArrived] once the final one is reached.
  void moveAlongPath(List<Vector2> waypoints, {VoidCallback? onArrived}) {
    followPath(waypoints, onArrived: onArrived);
  }

  @override
  void update(double dt) {
    super.update(dt);
    advanceAlongPath(dt);
  }

  @override
  void render(Canvas canvas) {
    if (isSelected) {
      final ringPaint = Paint()
        ..color = const Color(0xFFFFFFFF)
        ..style = PaintingStyle.stroke
        ..strokeWidth = size.y * 0.08;
      canvas.drawOval(Rect.fromLTWH(0, 0, size.x, size.y).inflate(size.y * 0.15), ringPaint);
    }

    final hullPaint = Paint()..color = const Color(0xFF5D4037);
    final sailPaint = Paint()..color = const Color(0xFFECEFF1);

    final hullRect = Rect.fromLTWH(0, size.y * 0.5, size.x, size.y * 0.5);
    canvas.drawRRect(
      RRect.fromRectAndRadius(hullRect, Radius.circular(size.y * 0.2)),
      hullPaint,
    );

    final sailPath = Path()
      ..moveTo(size.x * 0.5, 0)
      ..lineTo(size.x * 0.5, size.y * 0.55)
      ..lineTo(size.x * 0.15, size.y * 0.55)
      ..close();
    canvas.drawPath(sailPath, sailPaint);
  }

  @override
  void onTapDown(TapDownEvent event) {
    super.onTapDown(event);
    event.continuePropagation = false;
    game.requestBoard(this);
  }
}
