import 'dart:ui';

import 'package:flame/components.dart';

enum BuildingType { port, lumberjack }

enum ResourceNodeType { tree, berryBush, sticks, stones }

/// A tree, berry bush or pile of sticks, shared by everyone in the world.
/// [regrowsIn] is how long until it can be gathered from again (zero if it
/// can be right now), as of when this record was received.
class ResourceNodeRecord {
  final int id;
  final ResourceNodeType type;
  final double x;
  final double y;
  final Duration regrowsIn;

  const ResourceNodeRecord({
    required this.id,
    required this.type,
    required this.x,
    required this.y,
    this.regrowsIn = Duration.zero,
  });
}

/// A geographic island's position/size as generated by the backend - the
/// server is the single source of truth for the map layout, so every
/// player's client renders the same islands at the same coordinates.
class IslandLayout {
  final double centerX;
  final double centerY;
  final double radius;
  final bool isHome;

  const IslandLayout({
    required this.centerX,
    required this.centerY,
    required this.radius,
    required this.isHome,
  });
}

/// An already-built building fetched from the backend on startup, so it can
/// be rendered for whoever loads the app instead of only existing in the
/// session that originally built it.
class BuildingRecord {
  final int id;
  final BuildingType type;
  final double x;
  final double y;
  final int ownerId;
  final Color ownerColor;

  /// For a lumberjack: the wood it's holding (as of when this record was
  /// received), how fast that grows, and how much it can hold.
  final double storedWood;
  final double woodPerSecond;
  final double woodCapacity;

  const BuildingRecord({
    required this.id,
    required this.type,
    required this.x,
    required this.y,
    required this.ownerId,
    required this.ownerColor,
    this.storedWood = 0,
    this.woodPerSecond = 0,
    this.woodCapacity = 0,
  });
}

/// A walk or voyage: start at [from], then visit each point of [path] in
/// order at the mover's fixed speed. [elapsed] is how long ago it started,
/// so someone joining mid-way can fast-forward to where it is now.
class MovementRecord {
  final Vector2 from;
  final List<Vector2> path;
  final Duration elapsed;

  const MovementRecord({required this.from, required this.path, this.elapsed = Duration.zero});
}

/// A boat as stored on the backend, plus its voyage in progress if any.
class BoatRecord {
  final int id;
  final int ownerId;
  final double x;
  final double y;
  final MovementRecord? movement;

  const BoatRecord({
    required this.id,
    required this.ownerId,
    required this.x,
    required this.y,
    this.movement,
  });
}

/// Another player in this world. [x]/[y] is where they are (or are
/// heading, if [movement] is set); [boatId] is set while they're aboard a
/// boat, in which case they ride along with it.
class RemotePlayerRecord {
  final int userId;
  final String username;
  final Color color;
  final double x;
  final double y;
  final int? boatId;
  final MovementRecord? movement;

  const RemotePlayerRecord({
    required this.userId,
    required this.username,
    required this.color,
    required this.x,
    required this.y,
    this.boatId,
    this.movement,
  });
}
